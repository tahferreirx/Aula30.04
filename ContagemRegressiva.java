package Desafios;

public class ContagemRegressiva {
	public static void main(String[] args) {
		
		int numero = 100;

		System.out.println("Contagem regressiva de 100 até 0, pulando de 10 em 10:");

		while (numero >= 0) {
		System.out.println(numero);
		numero -= 10;
		        }

		System.out.println("Fim da contagem!");
		    }
		
	}


